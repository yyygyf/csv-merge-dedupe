import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';

const root = dirname(fileURLToPath(import.meta.url));
async function section(file, start, end) {
  const source = (await readFile(join(root, file), 'utf8')).replaceAll('\r\n', '\n');
  const a = source.indexOf(start), b = source.indexOf(end, a + start.length);
  if (a < 0 || b < 0) throw new Error(`Cannot locate browser-safe section in ${file}`);
  return source.slice(a, b).trimEnd();
}
const generated = '// Generated by node build-web-core.mjs from the unchanged CLI functions.\n' +
  '// Do not edit this file directly. No Node imports or network operations.\n\n' +
  (await Promise.all([
    section('merge.mjs', 'export function parseCsv', 'export function mergeTables'),
    section('compare.mjs', 'export function compareCsv', 'async function selfTest'),
    section('compare-report.mjs', 'const escapeHtml', 'async function main'),
  ])).join('\n\n') + '\n';
const target = join(root, 'web-core.mjs');
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')).replaceAll('\r\n', '\n') !== generated)
    throw new Error('web-core.mjs is out of sync; run node build-web-core.mjs');
  console.log('PASS: browser functions exactly match CLI sources');
} else {
  await writeFile(target, generated);
  console.log('Generated web-core.mjs');
}
